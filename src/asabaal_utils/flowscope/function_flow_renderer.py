    def _generate_nodes_js(self, nodes: List) -> str:
        """Generate JavaScript code for nodes."""
        js_lines = []
        for node in nodes:
            # Determine color and shape based on node type
            color_map = {
                'assignment': '#ffd700',  # Gold
                'conditional': '#ffa500',  # Orange
                'loop': '#ff9999',  # Light red
                'return': '#90ee90',  # Light green
                'try': '#dda0dd',  # Plum
                'except': '#f0e68c',  # Khaki
                'merge': '#d3d3d3',  # Light gray
            }
            
            shape_map = {
                'conditional': 'diamond',
                'loop': 'diamond',
                'merge': 'circle',
            }
            
            color = color_map.get(node.type, '#97c2fc')  # Default blue
            shape = shape_map.get(node.type, 'box')  # Default box
            
            # Convert single quotes to double quotes and use JSON encoding
            label_text = str(node.label).replace("\n", "\\n").replace("'", '"') if node.label else ''
            label = json.dumps(label_text, ensure_ascii=False)
            if len(label_text) > 30:
                label = json.dumps(label_text[:27] + '...', ensure_ascii=False)
            
            if node.label:
                label_clean = str(node.label).replace("'", '"')
                title_text = f"{label_clean}\\nLine: {str(node.line)}\\nType: {str(node.type)}"
            else:
                title_text = f"Line: {str(node.line)}\\nType: {str(node.type)}"
            # Use ensure_ascii=False to preserve Unicode characters properly
            title = json.dumps(title_text, ensure_ascii=False)
            
            js_line = f"""{{
                id: '{node.id}',
                label: {label},
                title: {title},
                color: '{color}',
                shape: '{shape}',
                font: {{size: 12}}
            }}"""
            js_lines.append(js_line)
        
        return ',\n            '.join(js_lines)
    
    def _generate_edges_js(self, edges: List[Dict[str, Any]]) -> str:
        """Generate JavaScript code for edges."""
        js_lines = []
        for edge in edges:
            label = edge.get('label', '') or ''
            label_json = json.dumps(str(label))
            js_lines.append(f"""{{
                from: '{edge['from']}',
                to: '{edge['to']}',
                label: {label_json},
                arrows: 'to',
                color: {{color: "#666666"}},
                font: {{size: 10, align: "middle"}}
            }}""")
        
        if not js_lines:
            return ''
        return ',\n            '.join(js_lines)
    
    def _create_static_flow_image(self, function_flow: FunctionFlow, image_path: Path):
        """Create a static PNG image of the function flow."""
        fig, ax = plt.subplots(1, 1, figsize=(12, 8))
        
        # Position nodes in a flow layout
        positions = {}
        level_height = 1.5
        node_spacing = 2.0
        
        # Create hierarchical layout
        node_count = len(function_flow.nodes)
        for i, node in enumerate(function_flow.nodes):
            positions[node.id] = (i % 4 * 2, (i // 4) * 1.5)
        
        # Add entry and exit points
        positions[function_flow.entry_point.id] = (0, 6)
        positions[function_flow.exit_point.id] = (node_count % 4 * 2, (node_count // 4) * 1.5 + 1)
        
        # Draw edges
        for edge in function_flow.edges:
            from_pos = positions[edge['from']]
            to_pos = positions[edge['to']]
            ax.annotate('', xy=to_pos, xytext=from_pos,
                       arrowprops=dict(arrowstyle='->', color='#666666', lw=1.5))
        
        # Draw nodes
        for node in function_flow.nodes:
            pos = positions[node.id]
            color_map = {
                'entry': '#90ee90',
                'exit': '#ff6b6b', 
                'assignment': '#ffd700',
                'conditional': '#ffa500',
                'loop': '#ff9999',
                'return': '#90ee90',
                'try': '#dda0dd'
            }
            color = color_map.get(node.type, '#97c2fc')
            
            # Choose node shape
            if node.type in ['entry', 'exit']:
                circle = Circle(pos, 0.4, color=color, ec='black', linewidth=2, zorder=10)
                ax.add_patch(circle)
            else:
                rect = FancyBboxPatch((pos[0]-0.5, pos[1]-0.3), 1.0, 0.6,
                                     boxstyle="round,pad=0.1", 
                                     facecolor=color, 
                                     edgecolor='black', 
                                     linewidth=1.5,
                                     zorder=10)
                ax.add_patch(rect)
            
            # Add labels
            label = str(node.label)[:20] + '...' if len(str(node.label)) > 20 else str(node.label)
            ax.text(pos[0], pos[1]-0.8, label, 
                    ha='center', va='top', fontsize=8, 
                    bbox=dict(boxstyle='round,pad=0.3', facecolor='white', alpha=0.8))
        
        # Set plot properties
        ax.set_xlim(-1, max(pos[0] for pos in positions.values()) + 1)
        ax.set_ylim(0, max(pos[1] for pos in positions.values()) + 1)
        ax.set_aspect('equal')
        ax.axis('off')
        
        # Add title
        ax.text(len(positions) / 2, max(pos[1] for pos in positions.values()) + 0.5, 
                f'Function Flow: {function_flow.function_name}', 
                ha='center', va='center', fontsize=16, fontweight='bold')
        
        plt.tight_layout()
        plt.savefig(image_path, dpi=150, bbox_inches='tight')
        plt.close()
    
    def _generate_flow_sequence_html(self, function_flow: FunctionFlow) -> str:
        """Generate HTML for flow sequence."""
        sequence_items = []
        for edge in function_flow.edges:
            sequence_items.append(f"<li>{edge['from']} → {edge['to']}</li>")
        return '\n'.join(sequence_items)
    
    def _generate_node_details_html(self, function_flow: FunctionFlow) -> str:
        """Generate HTML for node details."""
        node_items = []
        for node in function_flow.nodes:
            node_items.append(f"""
                <div class="node-item">
                    <strong>{node.id}:</strong> {node.type}<br>
                    <small>{node.label}</small><br>
                    <small>Line {node.line}</small>
                </div>
            """)
        return '\n'.join(node_items)
    
    def _generate_module_flows_html(self, module_flows: Dict[str, FunctionFlow], 
                                  module_name: str) -> str:
        """Generate HTML for all function flows in a module."""
        function_list = []
