class FunctionFlowRenderer:
    """Renders function flow visualizations."""
    
    def __init__(self, output_dir: Path):
        self.output_dir = output_dir
        self.function_flows_dir = output_dir / "function_flows"
        self.function_flows_dir.mkdir(parents=True, exist_ok=True)
    
    def render_function_flow(self, function_flow: FunctionFlow, use_dynamic: bool = True) -> Path:
        """Render a single function flow to HTML."""
        
        if use_dynamic:
            # Use the new dynamic generator
            flow_data = {
                'function_name': function_flow.function_name,
                'module': function_flow.module,
                'file_path': function_flow.file_path,
                'entry_point': function_flow.entry_point,
                'exit_point': function_flow.exit_point,
                'nodes': function_flow.nodes,
                'edges': function_flow.edges
            }
            
            # Create filename
            safe_function_name = function_flow.function_name.replace('.', '_').replace('<', '_').replace('>', '_')
            output_file = self.function_flows_dir / f"{safe_function_name}_flow.html"
            
            generate_dynamic_function_flow(
                flow_data,
                output_file,
                function_name=function_flow.function_name,
                module_name=function_flow.module
            )
        else:
            # Use the old static generator
            html_content = self._generate_function_flow_html(function_flow)
            
            # Create filename
            safe_function_name = function_flow.function_name.replace('.', '_').replace('<', '_').replace('>', '_')
            output_file = self.function_flows_dir / f"{safe_function_name}_flow.html"
            
            with open(output_file, 'w', encoding='utf-8') as f:
                f.write(html_content)
        
        return output_file
    
    def render_module_function_flows(self, module_flows: Dict[str, FunctionFlow], 
                                   module_name: str) -> Path:
        """Render all function flows for a module to a single HTML file."""
        html_content = self._generate_module_flows_html(module_flows, module_name)
        
        safe_module_name = module_name.replace('.', '_')
        output_file = self.function_flows_dir / f"{safe_module_name}_flows.html"
        
        with open(output_file, 'w', encoding='utf-8') as f:
            f.write(html_content)
        
        return output_file
    
    def save_function_flows_json(self, parser: FunctionFlowParser, module_name: str) -> Path:
        """Save function flows data as JSON for loading in visualizations."""
        safe_module_name = module_name.replace('.', '_')
        output_file = self.function_flows_dir / f"{safe_module_name}.json"
        
        # Create data structure for this module
        module_data = {
            'module': module_name,
            'function_flows': {
                name: flow.to_dict() 
                for name, flow in parser.function_flows.items()
            }
        }
        
        with open(output_file, 'w', encoding='utf-8') as f:
            json.dump(module_data, f, indent=2)
        
        return output_file
    
